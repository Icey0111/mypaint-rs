//! 构建期生成官方笔刷包索引。
//!
//! 目的：**零运行时开销**地把 196 支官方 .myb（CC0）内嵌进引擎 crate。
//!
//! - 笔刷 JSON 原文用 `include_str!` 内联到二进制，运行时不读盘、不解析即可列出列表；
//! - `description` / `notes` 等展示元数据在构建期解析好（运行期列表零解析成本）；
//! - **预览图 `{name}_prev.png` 也一并内嵌**：MyPaint 的 `ManagedBrush.get_preview()`
//!   （`gui/brushmanager.py:1242`）优先读盘上这份 128×128 的官方缩略图，
//!   只有取不到时才实时渲染。内嵌模式没有"盘上"，所以把 PNG 原文内联进来，
//!   语义与 MyPaint 的「优先用随附预览图」完全一致；
//! - 排序与分组名沿用官方 `order.conf`（与 MyPaint 笔刷列表顺序一致）。
//!
//! 生成物：`$OUT_DIR/brush_index.rs`，由 `src/brushlib.rs` 用 `include!` 引入。

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("assets").join("brushes");
    let order_conf = root.join("order.conf");

    println!("cargo:rerun-if-changed={}", root.display());
    println!("cargo:rerun-if-changed={}", order_conf.display());

    // ---- 1. 收集磁盘上全部 .myb ----
    let mut found: BTreeMap<String, (String, String)> = BTreeMap::new(); // key -> (group, name)
    for (group_dir, file) in walk_myb(&root) {
        let name = file.strip_suffix(".myb").unwrap_or(&file).to_string();
        let key = format!("{group_dir}/{name}");
        found.insert(key, (group_dir, name));
    }

    // 逐文件声明依赖：`include_bytes!` 的 PNG 与 `include_str!` 的 JSON 改动都要重新生成
    for (group, name) in found.values() {
        println!(
            "cargo:rerun-if-changed={}",
            root.join(group).join(format!("{name}.myb")).display()
        );
        println!(
            "cargo:rerun-if-changed={}",
            root.join(group).join(format!("{name}_prev.png")).display()
        );
    }

    // ---- 2. 官方 order.conf 决定顺序与分组展示名 ----
    let order = read_order_conf(&order_conf);
    let mut ordered_keys: Vec<String> = Vec::new();
    let mut group_display: BTreeMap<String, String> = BTreeMap::new();
    for (display_group, key) in &order {
        if !found.contains_key(key) {
            println!("cargo:warning=order.conf 中的 {key} 不存在于 assets/brushes，已忽略");
            continue;
        }
        let group = found[key].0.clone();
        group_display
            .entry(group)
            .or_insert_with(|| display_group.clone());
        ordered_keys.push(key.clone());
    }
    // order.conf 未覆盖的（自定义新增笔刷）按 key 排序追加
    for key in found.keys() {
        if !ordered_keys.contains(key) {
            ordered_keys.push(key.clone());
        }
    }

    // ---- 3. 构建期解析展示元数据 ----
    let mut out = String::new();
    out.push_str("// @generated by build.rs —— 官方笔刷包索引，请勿手工编辑。\n\n");
    out.push_str("/// 一条内嵌笔刷记录。`json` 为 .myb 原文（编译期内联）。\n");
    out.push_str("pub struct IndexedBrush {\n");
    out.push_str("    /// 分组 id（= 资产目录名）\n    pub group: &'static str,\n");
    out.push_str(
        "    /// 分组展示名（来自官方 order.conf）\n    pub group_display: &'static str,\n",
    );
    out.push_str("    /// 笔刷名（= 文件名去扩展名）\n    pub name: &'static str,\n");
    out.push_str("    /// 展示名（优先取 .myb 的 description，缺省为文件名）\n    pub display: &'static str,\n");
    out.push_str("    /// .myb 的 notes 字段（作者/授权/说明，用于工具提示）\n    pub notes: &'static str,\n");
    out.push_str(
        "    /// 相对 assets/brushes 的路径，形如 `classic/brush`\n    pub path: &'static str,\n",
    );
    out.push_str("    pub json: &'static str,\n");
    out.push_str("    /// 随附的 `{name}_prev.png` 原文（MyPaint `ManagedBrush.get_preview()` 的首选来源；\n");
    out.push_str("    /// 官方包 196 支全部具备，缺失时为 `None` 并回退到实时渲染）\n");
    out.push_str("    pub prev: Option<&'static [u8]>,\n}\n\n");

    let _ = writeln!(out, "pub static INDEXED: &[IndexedBrush] = &[");
    let mut meta_errors = 0usize;
    let mut missing_prev: Vec<String> = Vec::new();
    for key in &ordered_keys {
        let (group, name) = &found[key];
        let rel = format!("{group}/{name}.myb");
        let abs = root.join(&rel);
        let (display, notes) = match read_meta(&abs) {
            Ok(m) => m,
            Err(e) => {
                meta_errors += 1;
                println!("cargo:warning=解析 {rel} 元数据失败: {e}（回退为文件名）");
                (String::new(), String::new())
            }
        };
        let display = if display.trim().is_empty() {
            name.clone()
        } else {
            display.trim().to_string()
        };
        let gd = group_display
            .get(group)
            .cloned()
            .unwrap_or_else(|| group.clone());
        // 预览图：MyPaint 的 `_get_fileprefix()` + "_prev.png"（brushmanager.py:1446）
        let prev_rel = format!("{group}/{name}_prev.png");
        let prev = if root.join(&prev_rel).is_file() {
            format!(
                "Some(include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/brushes/{}\")).as_slice())",
                esc(&prev_rel)
            )
        } else {
            missing_prev.push(key.clone());
            "None".to_string()
        };
        let _ = writeln!(
            out,
            "    IndexedBrush {{ group: \"{}\", group_display: \"{}\", name: \"{}\", display: \"{}\", notes: \"{}\", path: \"{}\", json: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/brushes/{}\")), prev: {} }},",
            esc(group),
            esc(&gd),
            esc(name),
            esc(&display),
            esc(notes.trim()),
            esc(key),
            esc(&rel),
            prev,
        );
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("brush_index.rs");
    std::fs::write(&dest, out).expect("写入 brush_index.rs 失败");
    println!(
        "cargo:warning=官方笔刷索引已生成：{} 支（元数据解析失败 {meta_errors} 支，缺 _prev.png {} 支）",
        ordered_keys.len(),
        missing_prev.len()
    );
    for k in missing_prev.iter().take(10) {
        println!("cargo:warning=缺少预览图：{k}_prev.png（将回退到实时渲染）");
    }
}

/// 递归收集 `*.myb`，返回 `(子目录名, 文件名)`。
fn walk_myb(root: &Path) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(root) else {
        return out;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            let Some(group) = path
                .file_name()
                .and_then(|s| s.to_str())
                .map(str::to_string)
            else {
                continue;
            };
            let Ok(files) = std::fs::read_dir(&path) else {
                continue;
            };
            for f in files.flatten() {
                let fp = f.path();
                if fp.extension().and_then(|e| e.to_str()) == Some("myb") {
                    if let Some(name) = fp.file_name().and_then(|s| s.to_str()) {
                        out.push((group.clone(), name.to_string()));
                    }
                }
            }
        }
    }
    out.sort();
    out
}

/// 读 `order.conf` → `[(分组展示名, 笔刷 key)]`，保持官方顺序。
fn read_order_conf(path: &Path) -> Vec<(String, String)> {
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    let mut group = String::from("Brushes");
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(rest) = line.strip_prefix("Group:") {
            group = rest.trim().to_string();
            continue;
        }
        out.push((group.clone(), line.to_string()));
    }
    out
}

/// 只取展示需要的两个字段：`description`、`notes`。
fn read_meta(path: &Path) -> Result<(String, String), String> {
    let text = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
    let v: serde_json::Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;
    let get = |k: &str| {
        v.get(k)
            .and_then(|x| x.as_str())
            .unwrap_or_default()
            .to_string()
    };
    Ok((get("description"), get("notes")))
}

/// 转义成 Rust 字符串字面量内容。
fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out
}
